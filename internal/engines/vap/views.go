const (
	cmdPolicies = Prefix + "/pol"
	cmdBindings = Prefix + "/b"
)

// Views implements engine.Engine.
func (e *Engine) Views() []engine.View {
	return []engine.View{
		{
			Command: cmdPolicies, Aliases: []string{Prefix + "/policies", Prefix + "/validatingadmissionpolicies"},
			Title: "ValidatingAdmissionPolicies", Description: "native admission policies (G shows generated ones)",
			Columns: []engine.Column{
				{Title: "NAME", Role: engine.RoleName}, {Title: "FAILURE"}, {Title: "PARAMS"}, {Title: "BINDINGS", Role: engine.RoleCount},
				{Title: "ENFORCEMENT", Role: engine.RoleMode}, {Title: "GENERATED BY", Flex: true},
			},
			DefaultSort: engine.Sort{Role: engine.RoleName},
			Rows:        func(f engine.Filter) ([]engine.Row, error) { return e.policyRows(f), nil },
			Keys: []engine.ViewKey{{Key: "G", Help: "generated", Do: func() string {
				if e.showGenerated.Load() {
					e.showGenerated.Store(false)
					return "hiding generated policies (Gatekeeper, Kyverno)"
				}
				e.showGenerated.Store(true)
				return "showing generated policies (Gatekeeper, Kyverno)"
			}}},
		},
		{
			Command: cmdBindings, Aliases: []string{Prefix + "/bindings", Prefix + "/validatingadmissionpolicybindings"},
			Title: "ValidatingAdmissionPolicyBindings", Description: "bindings: actions, params, match resources",
			Columns: []engine.Column{
				{Title: "NAME", Role: engine.RoleName}, {Title: "POLICY", Role: engine.RoleTarget}, {Title: "ACTIONS", Role: engine.RoleMode},
				{Title: "PARAM"}, {Title: "MATCH", Flex: true}, {Title: "AGE", Role: engine.RoleAge},
			},
			DefaultSort: engine.Sort{Role: engine.RoleName},
			Rows:        func(f engine.Filter) ([]engine.Row, error) { return e.bindingRows(f), nil },
		},
	}
}

func matchesEngine(f engine.Filter) bool { return f.Engine == "" || f.Engine == Name }

func (e *Engine) policyRows(f engine.Filter) []engine.Row {
	if !matchesEngine(f) {
		return nil
	}
	s := e.snapshot()
	show := e.showGenerated.Load()
	var rows []engine.Row
	for i := range s.policies {
		p := &s.policies[i]
		if (p.generatedBy != "" && !show) || !f.MatchesPolicy(p.Key()) {
			continue
		}
		raw := p.Raw
		row := engine.Row{
			ID: p.Name,
			Cells: []engine.Cell{
				engine.TextCell(p.Name), engine.TextCell(failurePolicy(raw)), engine.TextCell(paramKind(raw)),
				engine.CountCell(len(p.bindings)), engine.ModeCell(p.Enforcement), engine.TextCell(dash(p.generatedBy)),
			},
			Object: raw,
			Detail: func() (engine.Detail, error) { return policyDetail(p), nil },
			Drill:  &engine.Target{Command: cmdBindings, Filter: engine.Filter{Engine: Name, PolicyName: p.Name}},
		}
		if p.generatedBy == "" {
			key := p.Key()
			row.Policy = &key
		}
		rows = append(rows, row)
	}
	return rows
}

func (e *Engine) bindingRows(f engine.Filter) []engine.Row {
	if !matchesEngine(f) {
		return nil
	}
	s := e.snapshot()
	var rows []engine.Row
	for _, b := range s.bindings {
		policy, _, _ := unstructured.NestedString(b.Object, "spec", "policyName")
		if f.PolicyName != "" && f.PolicyName != policy {
			continue
		}
		if p, ok := s.byName[policy]; ok && p.generatedBy != "" && !e.showGenerated.Load() && f.PolicyName == "" {
			continue
		}
		pref := model.ObjectRef{Group: group, Version: e.gvr(resourcePolicy).Version, Kind: kindPolicy, Name: policy}
		rows = append(rows, engine.Row{
			ID: b.GetName(),
			Cells: []engine.Cell{
				engine.TextCell(b.GetName()), engine.TextCell(policy), engine.TextCell(dash(strings.Join(actionsOf(b), ","))),
				engine.TextCell(paramSummary(b)), engine.TextCell(matchSummary(b)), engine.AgeCell(b.GetCreationTimestamp().Time),
			},
			Object: b,
			Ref:    &pref,
			Detail: func() (engine.Detail, error) { return bindingDetail(b), nil },
		})
	}
	return rows
}

func failurePolicy(o *unstructured.Unstructured) string {
	fp, _, _ := unstructured.NestedString(o.Object, "spec", "failurePolicy")
	if fp == "" {
		fp = "Fail" // the API default
	}
	return fp
}

func paramKind(o *unstructured.Unstructured) string {
	k, _, _ := unstructured.NestedString(o.Object, "spec", "paramKind", "kind")
	return dash(k)
}

func paramSummary(b *unstructured.Unstructured) string {
	pr, ok, _ := unstructured.NestedMap(b.Object, "spec", "paramRef")
	if !ok {
		return "-"
	}
	if _, sel := pr["selector"]; sel {
		return "selector"
	}
	return nsName(enginekit.Str(pr, "namespace"), enginekit.Str(pr, "name"))
}

// matchSummary condenses matchResources to one line.
func matchSummary(b *unstructured.Unstructured) string {
	mr, ok, _ := unstructured.NestedMap(b.Object, "spec", "matchResources")
	if !ok || len(mr) == 0 {
		return "the policy's matchConstraints"
	}
	var parts []string
	for _, f := range []string{"namespaceSelector", "objectSelector"} {
		if sel, ok := mr[f].(map[string]any); ok && len(sel) > 0 {
			parts = append(parts, f)
		}
	}
	if rules := enginekit.Slice(mr, "resourceRules"); len(rules) > 0 {
		parts = append(parts, fmt.Sprintf("%d resource rules", len(rules)))
	}
	if rules := enginekit.Slice(mr, "excludeResourceRules"); len(rules) > 0 {
		parts = append(parts, fmt.Sprintf("%d exclusions", len(rules)))
	}
	if len(parts) == 0 {
		return "the policy's matchConstraints"
	}
	return strings.Join(parts, " · ")
}

func policyDetail(p *vapPolicy) engine.Detail {
	o := p.Raw
	gen := "-"
	if p.generatedBy != "" {
		gen = p.generatedBy + " (managed by that engine; edits are reverted)"
	}
	d := engine.Detail{Title: "ValidatingAdmissionPolicy " + p.Name, Sections: []engine.Section{
		{Title: "Summary", Body: kv("Failure policy", failurePolicy(o)+" — "+failureMeaning(failurePolicy(o)),
			"Param kind", paramKindFull(o), "Enforcement", p.Enforcement.String(), "Bindings", fmt.Sprint(len(p.bindings)),
			"Generated by", gen)},
		{Title: "Match constraints", Body: enginekit.NestedYAML(o, "(none)", "spec", "matchConstraints"), Language: "yaml"},
	}}
	for _, src := range p.Sources {
		d.Sections = append(d.Sections, engine.Section{Title: "Validations (CEL)", Body: src.Code, Language: string(model.LangCEL)})
	}
	for _, f := range []struct{ title, field string }{{"Match conditions", "matchConditions"}, {"Variables", "variables"}, {"Audit annotations", "auditAnnotations"}} {
		if v := enginekit.Slice(o.Object, "spec", f.field); len(v) > 0 {
			d.Sections = append(d.Sections, engine.Section{Title: f.title, Body: enginekit.YAML(v), Language: "yaml"})
		}
	}
	if w := enginekit.Slice(o.Object, "status", "typeChecking", "expressionWarnings"); len(w) > 0 {
		d.Sections = append(d.Sections, engine.Section{Title: "Type-checking warnings", Body: enginekit.YAML(w), Language: "yaml"})
	}
	var b strings.Builder
	for _, bd := range p.bindings {
		fmt.Fprintf(&b, "%s: actions %s, param %s, match %s\n", bd.GetName(), dash(strings.Join(actionsOf(bd), ",")), paramSummary(bd), matchSummary(bd))
	}
	body := strings.TrimRight(b.String(), "\n")
	if body == "" {
		body = "Not bound: no binding references this policy, so it enforces nothing."
	}
	d.Sections = append(d.Sections, engine.Section{Title: "Bindings", Body: body})
	return d
}

func bindingDetail(b *unstructured.Unstructured) engine.Detail {
	return engine.Detail{Title: "ValidatingAdmissionPolicyBinding " + b.GetName(), Sections: []engine.Section{
		{Title: "Summary", Body: kv("Policy", enginekit.NestedYAML(b, "-", "spec", "policyName"),
			"Actions", dash(strings.Join(actionsOf(b), ",")), "Param", paramSummary(b))},
		{Title: "Param ref", Body: enginekit.NestedYAML(b, "(none)", "spec", "paramRef"), Language: "yaml"},
		{Title: "Match resources", Body: enginekit.NestedYAML(b, "(the policy's matchConstraints)", "spec", "matchResources"), Language: "yaml"},
	}}
}

func failureMeaning(fp string) string {
	if fp == "Ignore" {
		return "evaluation errors admit the request (fail open)"
	}
	return "evaluation errors reject the request"
}

func paramKindFull(o *unstructured.Unstructured) string {
	pk, ok, _ := unstructured.NestedMap(o.Object, "spec", "paramKind")
	if !ok {
		return "-"
	}
	return enginekit.Str(pk, "apiVersion") + " " + enginekit.Str(pk, "kind")
}

func kv(pairs ...string) string { return enginekit.KV(pairs...) }

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return strings.TrimSpace(s)
}
